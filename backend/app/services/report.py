"""A take-away report of one analysis, so nothing is lost when the session ends.

It holds results only, never the resume text or personal details (quotes come from the
masked text), and SkillBridge keeps no copy.
"""

import html
from datetime import date

from app.services.analysis import Analysis, SkillMatch
from app.services.learning import LEVEL_NAMES

NOTE = ("Generated by SkillBridge from a masked copy of your resume. Guidance, not a guarantee "
        "of employment. SkillBridge keeps no copy of your resume or this report.")
STATUS = {"meets": "Meets", "below": "Below", "missing": "Not shown"}


def _todo(m: SkillMatch, analysis: Analysis) -> str:
    steps = [s for s in analysis.learning if s.skill == m.skill]
    texts = [s.text for s in steps]
    plan = "; then ".join([texts[0]] + [t[0].lower() + t[1:] for t in texts[1:]]) if texts else ""
    if m.related:
        close = (f"Related, not the same: you show {m.related} ({LEVEL_NAMES[m.related_level]}). "
                 f"Say how it transfers, and be clear you haven't used {m.skill} yet.")
        return f"{close} {plan}".strip()
    return plan or "—"


BLOCKER_NAME = {"work_authorisation": "Work authorisation", "location": "Location or work arrangement",
                "degree": "Degree", "experience": "Years of experience"}


def blocker_lines(a: Analysis) -> list[tuple[str, str, str, str]]:
    """(label, status word, the job's words, note) for the 'likely auto-filters' panel."""
    return [(BLOCKER_NAME[b.kind], "Check" if b.status == "check" else "OK", b.jd_quote, b.note) for b in a.blockers]


def render_markdown(a: Analysis, on: date | None = None) -> str:
    on = on or date.today()
    level = f" · {a.seniority.title()}" if a.seniority else ""
    out = [f"# SkillBridge report: {a.title}{level}", f"{on.isoformat()}", "", "## Summary", a.summary, ""]
    if a.fit:
        out += [f"## Fit: {a.fit.verdict}", a.fit.advice, " ".join(a.fit.reasons), ""]
    if a.blockers:
        out += ["## Likely auto-filters: check these first",
                "Employers' systems often filter on these before anyone reads your skills. A hint, not a verdict."]
        out += [f"- **{label}** ({status}): \"{quote}\". {note}" for label, status, quote, note in blocker_lines(a)]
        out += [""]
    if a.soft["shown"] or a.soft["interview"]:
        out += ["## Ways of working the job mentions (not scored)"]
        out += [f"- Shown: {m.skill}" for m in a.soft["shown"]]
        out += [f"- Prepare an example for the interview: {m.skill} (no change to your resume needed)"
                for m in a.soft["interview"]]
        out += [""]
    if a.focus:
        out += ["## Start here", ", ".join(f"{i}. {f}" for i, f in enumerate(a.focus, 1)), a.focus_reason, ""]
    out += [f"## Learn: what's missing ({len(a.gaps)})"]
    if a.gaps:
        out += ["| Skill | Status | The job asks | Your resume | What to do |", "| --- | --- | --- | --- | --- |"]
        for m in a.gaps:
            out.append(f"| {m.skill} | {STATUS[m.status]} ({LEVEL_NAMES[m.current]} → {LEVEL_NAMES[m.needed]}"
                       f"{', must-have' if m.must_have else ''}) | \"{m.job_quote}\" | "
                       f"{chr(34) + m.resume_quote + chr(34) if m.resume_quote else 'Not shown'} | {_todo(m, a)} |")
    else:
        out.append("Your resume shows every skill this job asks for.")
    if a.show_better:
        out += ["", "## Show better: you have it, your resume hides it"]
        out += [f"- {b.skill}: {b.text}" + (f' (your line: "{b.resume_line}")' if b.resume_line else "")
                for b in a.show_better]
    if a.strengths:
        out += ["", "## Strengths"] + [f"- {m.skill}: \"{m.resume_quote}\"" for m in a.strengths]
    out += ["", "## Learning plan"]
    out += [f"{i}. {s.text}" + (f": {', '.join(s.topics)}" if s.topics else "") + f" ({s.reason})"
            for i, s in enumerate(a.learning, 1)] or ["Nothing to learn for this job."]
    if a.projects:
        out += ["", "## Portfolio projects"]
        out += [f"- **{p.title}**: {p.build} Shows {', '.join(p.skills)}. The job says: \"{p.job_quote}\""
                for p in a.projects]
    out += ["", "## Resume"]
    out += [f"- {'Pass' if c['ok'] else 'Review'} · {c['area']}: {c['text']}" for c in a.checks]
    if a.changes:
        out += ["", "## What changed after your answers"]
        out += [f"- {c.skill}: {LEVEL_NAMES[c.before]} → {LEVEL_NAMES[c.after]}. You said: \"{c.said}\". {c.where}"
                for c in a.changes]
    asked = a.asked()
    if asked:
        out += ["", "## Your questions and answers (only your answers can add new facts)"]
        for q in asked:
            out.append(f"- {q['topic']} {q['issue']} {q['question']}\n  Your answer: {q['answer'] or 'not answered'}")
            if q["takeaway"]:
                out.append(f"  What this means: {q['takeaway']}")
            if q["effects"]:
                out.append(f"  Changed your plan: {'; '.join(q['effects'])}")
            if q["rewrite"]:
                out.append(f"  Suggested line: \"{q['rewrite']}\"")
    return "\n".join(out + ["", "---", NOTE, ""])


