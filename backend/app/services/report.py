def render_html(a: Analysis, on: date | None = None) -> str:
    e = html.escape
    on = on or date.today()
    must_gaps = sum(1 for m in a.gaps if m.must_have)

    issues = "".join(
        f'<div class="issue"><div><div class="skill">{e(m.skill)}</div>'
        f'<div class="status {m.status}">{STATUS[m.status]} · {LEVEL_NAMES[m.current]} → {LEVEL_NAMES[m.needed]}</div>'
        f'<div class="must">{"Must-have" if m.must_have else "A plus"}</div></div>'
        f'<div><div class="label">The job asks</div><div class="quote">"{e(m.job_quote)}"</div>'
        f'<div class="label" style="margin-top:6px">Your resume</div>'
        f'<div class="quote">{chr(34) + e(m.resume_quote) + chr(34) if m.resume_quote else "Not shown"}</div>'
        f'<div class="todo">{e(_todo(m, a))}</div></div></div>'
        for m in a.gaps) or "<p>Your resume shows every skill this job asks for.</p>"
    show = "".join(f'<div class="check"><span class="pass">Show</span><span><b>{e(b.skill)}</b></span>'
                   f'<span>{e(b.text)}' + (f' <span class="muted">Your line: "{e(b.resume_line)}"</span>' if b.resume_line else "")
                   + '</span></div>' for b in a.show_better)
    strengths = (f'<h2>Strengths</h2><p class="muted small">{e(", ".join(m.skill for m in a.strengths))}</p>'
                 if a.strengths else "")
    blockers = ""
    if a.blockers:
        blockers = ('<h2>Likely auto-filters: check these first</h2><p class="muted small">Employers\' systems often filter '
                    'on these before anyone reads your skills. A hint, not a verdict.</p>'
                    + "".join(f'<div class="check"><span class="{"review" if st == "Check" else "pass"}">{st}</span>'
                              f'<span><b>{e(label)}</b></span><span>"{e(q)}" {e(note)}</span></div>'
                              for label, st, q, note in blocker_lines(a)))
    soft = ""
    if a.soft["shown"] or a.soft["interview"]:
        soft = ('<h2>Ways of working the job mentions (not scored)</h2><p class="muted small">'
                + (f'Shown on your resume: {e(", ".join(m.skill for m in a.soft["shown"]))}. ' if a.soft["shown"] else "")
                + (f'Prepare one real example for the interview: {e(", ".join(m.skill for m in a.soft["interview"]))}. '
                   "You don't need a soft-skills list on your resume." if a.soft["interview"] else "") + "</p>")
    strengths = blockers + strengths + soft
    if show:
        strengths = f"<h2>Show better: you have it, your resume hides it</h2>{show}" + strengths

    plan = "".join(
        f"<li><b>{e(s.text)}</b> <span class='muted small'>· {e(s.reason)}</span>"
        + (f"<div class='topics'>Key topics: {e(', '.join(s.topics))}</div>" if s.topics else "")
        + "</li>" for s in a.learning)
    plan_html = f'<ol class="plan">{plan}</ol>' if plan else "<p>Nothing to learn for this job.</p>"

    projects = "".join(
        f'<div class="project"><b>{e(p.title)}</b><p>{e(p.build)}</p>'
        f'<p class="small muted">Shows {e(", ".join(p.skills))} · The job says <span class="quote">"{e(p.job_quote)}"</span></p></div>'
        for p in a.projects)

    checks = "".join(
        f'<div class="check"><span class="{"pass" if c["ok"] else "review"}">{"Pass" if c["ok"] else "Review"}</span>'
        f'<span><b>{e(c["area"])}</b></span><span>{e(c["text"])}</span></div>' for c in a.checks)
    questions = "".join(
        f'<div class="q"><div class="quote">{e(q["topic"])}</div><p class="muted small">{e(q["issue"])}</p>'
        f'<p><b>{e(q["question"])}</b></p>'
        + (f'<p><b>Your answer:</b> {e(q["answer"])}</p>' if q["answer"] else '<p class="muted">Not answered.</p>')
        + (f'<p><b>What this means:</b> {e(q["takeaway"])}</p>' if q["takeaway"] else '')
        + (f'<p><b>Changed your plan:</b> {e("; ".join(q["effects"]))}</p>' if q["effects"] else '')
        + (f'<p><b>Suggested line:</b> "{e(q["rewrite"])}"</p>' if q["rewrite"] else '')
        + '</div>' for q in a.asked())
    changes = "".join(
        f'<div class="check"><span class="pass">Up</span><span><b>{e(c.skill)}</b> '
        f'{LEVEL_NAMES[c.before]} → {LEVEL_NAMES[c.after]}</span>'
        f'<span>You said "{e(c.said)}". {e(c.where)}</span></div>' for c in a.changes)

    level = f" · {e(a.seniority.title())}" if a.seniority else ""
    facts = (f'<div><span>Requirements</span><b>{len(a.matches)}</b></div>'
             f'<div><span>Already meet</span><b>{len(a.matches) - len(a.gaps)}</b></div>'
             f'<div><span>Gaps</span><b>{len(a.gaps)}</b></div>'
             f'<div><span>Must-have gaps</span><b>{must_gaps}</b></div>')
    return ("<!doctype html><html lang='en'><head><meta charset='utf-8'>"
            "<meta name='viewport' content='width=device-width, initial-scale=1'>"
            f"<title>SkillBridge report · {e(a.title)}</title><style>{CSS}</style></head><body><main class='page'>"
            f"<header><div><div class='eyebrow'>SkillBridge report</div><h1>{e(a.title)}{level}</h1>"
            f"<div class='muted small'>Your resume compared with this job description</div></div>"
            f"<div class='meta'>{on.strftime('%d %B %Y')}</div></header>"
            f"<div class='facts'>{facts}</div>"
            + (f"<div class='q' style='margin-top:14px'><b>{e(a.fit.verdict)}</b><p>{e(a.fit.advice)}</p>"
               f"<p class='muted small'>{e(' '.join(a.fit.reasons))}</p></div>" if a.fit else "")
            + f"<h2>Summary</h2><p>{e(a.summary)}</p>"
            + (f"<h2>Start here</h2><ol class='plan'>{''.join(f'<li><b>{e(f)}</b></li>' for f in a.focus)}</ol>"
               f"<p class='muted small'>{e(a.focus_reason)}</p>" if a.focus else "")
            + f"<h2>Learn: what's missing</h2>{issues}{strengths}"
            f"<h2>Learning plan</h2>{plan_html}"
            + (f"<h2>Portfolio projects</h2>{projects}" if projects else "")
            + f"<h2>Resume</h2>{checks}"
            + (f"<h2>What changed after your answers</h2>{changes}" if changes else "")
            + (f"<h2 style='margin-top:20px'>Your questions and answers</h2>"
               f"<p class='muted small'>Only your answers can add new facts to your resume.</p>{questions}"
               if questions else "")
            + f"<footer>{e(NOTE)}{e(_review_note(a))}</footer></main></body></html>")


def _review_note(a: Analysis) -> str:
    if not a.review:
        return ""
    tries = len(a.review["attempts"])
    return (" Checked by an automatic reviewer" + (f" after {tries} drafts." if tries > 1 else ".")
            if a.review["passed"] else " An automatic reviewer flagged parts of this advice; read it critically.")
